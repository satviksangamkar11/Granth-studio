"""First SDXL + IP-Adapter keyframe test for the PROVISIONAL 45-second pilot, through GranthStudio's existing pipeline code (not a standalone generator).

  python scripts/sdxl_first_test.py --execute --workdir W --models-dir COMFYUI_ROOT --comfy-url http://127.0.0.1:PORT --gpu-index 0 --reference-image PNG ...

What runs: the provisional pilot project (scripts/pilot/build_pilot_project.py) is built under WORKDIR/project; research and canon are approved AT RUN TIME for the provisional technical
test under the named owner (never in the shipped files); the supplied painting is imported as the PROVISIONAL external identity/style reference of the main character and of the
location; the keyframe request for one scene is built by keyframes.keyframe_request (frozen style v1, narrator not drawn) and generated by keyframes.sdxl_generate. A control image with
the same prompt and seed but NO reference shows what the identity conditioning changes. The receipt records every hash, the live node check (ComfyUI /object_info through
ComfyBackend.require_nodes and require_model_files), timing and VRAM context. A PASS means technically valid images only: style fidelity and identity are judged by a human, and an
external reference never validates the SDXL stage by itself (the generated image is the evidence).
For this run only, the temporary project's models.yaml sets sdxl.status 'validated' and the workflow copy '_status: validated' so the existing gates let a validation run proceed; the
repository files keep 'unvalidated'. No retry: one attempt per image, out-of-memory stops the stage.
"""
