def _load(name: str, path: Path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


bp = _load("build_pilot_project", ROOT / "scripts" / "pilot" / "build_pilot_project.py")
lt = _load("ltx_first_test", ROOT / "scripts" / "ltx_first_test.py")        # reuse: execution gates, GPU listing, log excerpts, OOM markers, hashes
PINS = yaml.safe_load((ROOT / "config" / "pilot_sdxl_pins.yaml").read_text(encoding="utf-8"))
LTX_PINS = yaml.safe_load((ROOT / "config" / "ltx_098_pins.yaml").read_text(encoding="utf-8"))
OWNER_NOTE = "provisional technical test; owner instruction 2026-10-23 (docs/pilot/SDXL_DOWNLOAD_APPROVAL.md)"
MAIN_CHARACTER, LOCATION = "chr_gajanan_maharaj", "loc_devidas_house_road"


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--workdir", required=True, type=Path)
    parser.add_argument("--models-dir", required=True, type=Path, help="ComfyUI root holding models/checkpoints, ipadapter, clip_vision, vae")
    parser.add_argument("--comfy-url", default="http://127.0.0.1:8188")
    parser.add_argument("--reference-image", required=True, type=Path, help="the owner's painting, used as PROVISIONAL external identity/style reference")
    parser.add_argument("--visual", default="vis_s1_kf", help="which scene keyframe to generate (vis_s1_kf, vis_s2_kf or vis_s3_kf)")
    parser.add_argument("--gpu-index", type=int, choices=[0, 1])
    parser.add_argument("--comfy-log", type=Path)
    parser.add_argument("--worker-pid", type=int)
    parser.add_argument("--cuda-visible-devices")
    parser.add_argument("--min-free-vram-mb", type=float, default=10000)
    parser.add_argument("--min-ram-mb", type=float, default=12000)
    parser.add_argument("--min-disk-gb", type=float, default=30)
    parser.add_argument("--min-session-s", type=float, default=1800)
    parser.add_argument("--other-gpu-idle-mb", type=float, default=800)
    parser.add_argument("--allow-other-gpu-busy", action="store_true")
    parser.add_argument("--skip-control", action="store_true", help="skip the no-reference control image")
    parser.add_argument("--execute", action="store_true")
    return parser


def pinned_files() -> dict[str, dict]:
    return {item["role"]: item for item in PINS["files"]}


def model_path(models_dir: Path, item: dict) -> Path:
    return models_dir / item["dest_dir"] / item["name"]


def verify_files(models_dir: Path) -> list[str]:
    """Every pinned file must exist with its exact SHA-256; the receipt records what was seen."""
    problems = []
    for item in PINS["files"]:
        path = model_path(models_dir, item)
        if not path.is_file():
            problems.append(f"missing {path}")
        elif lt.sha256_file(path) != item["sha256"]:
            problems.append(f"{item['name']}: SHA-256 differs from the pin")
    return problems


def prepare_project(args: argparse.Namespace):
    from granthstudio.config import load_models, load_project
    if (args.workdir / "project").exists():
        raise RuntimeError("the workdir already holds a project: a fresh --workdir is required (run-time approvals are only ever applied to a project this run generated)")
    root = bp.build(args.workdir / "project")
    for name in ("research", "canon", "episodes"):                                            # approvals are written here: every one must stay inside this run's own project
        if not (root / name).resolve().is_relative_to(args.workdir.resolve()):
            raise RuntimeError(f"{name} directory leaves the workdir")
    artifacts = args.workdir / "artifacts"                                                    # generated media live in the run's workspace, never in the repository
    artifacts.mkdir(parents=True, exist_ok=True)
    config = yaml.safe_load((root / "config" / "project.yaml").read_text(encoding="utf-8"))
    config["artifacts_dir"] = str(artifacts)
    (root / "config" / "project.yaml").write_text(yaml.safe_dump(config, sort_keys=False), encoding="utf-8")
    project = load_project(root)
    files = pinned_files()
    template = root / "workflows" / "comfyui" / "sdxl_keyframe.json"
    candidate = json.loads((ROOT / PINS["workflow"]["api_candidate"]).read_text(encoding="utf-8"))
    candidate["_status"] = "validated"                                                       # run-only: the repository candidate stays "unvalidated"
    candidate["_note"] = "VALIDATION RUN COPY of workflows/comfyui/sdxl_ipadapter_keyframe.candidate.json; validity is decided by the human review, not by this flag"
    template.write_text(json.dumps(candidate, indent=2), encoding="utf-8")
    models = load_models(project)
    checkpoint = model_path(args.models_dir, files["sdxl_checkpoint"])
    width, height = PINS["workflow"]["size"]
    models["comfyui"]["base_url"] = args.comfy_url
    models["sdxl"].update(checkpoint_file=files["sdxl_checkpoint"]["name"], checkpoint_sha256=lt.sha256_file(checkpoint), checkpoint_path=str(checkpoint.resolve()),
                          workflow_template="workflows/comfyui/sdxl_keyframe.json", width=width, height=height, status="validated",
                          identity_conditioning={"method": "ip_adapter_plus_sdxl_vit_h", "reference_slots": PINS["workflow"]["reference_slots"]})
    commit = lt.git_head(args.models_dir) or PINS["comfyui"]["commit"]
    models["ltx"]["runtime"] = {"files": {"checkpoint": {"path": str(checkpoint), "sha256": models["sdxl"]["checkpoint_sha256"]}, "vae": None,
                                           "text_encoder": {"path": str(checkpoint), "sha256": models["sdxl"]["checkpoint_sha256"]}},   # schema slot only: this SDXL run uses no LTX text encoder
                                "comfyui_commit": commit, "node_pack_commit": PINS["custom_nodes"][0]["commit"], "gpu": "T4", "precision": "fp16", "width": width, "height": height}
    from granthstudio.config import dump_yaml
    dump_yaml(root / "config" / "models.yaml", models)
    runtime = yaml.safe_load((root / "config" / "runtime.yaml").read_text(encoding="utf-8"))
    runtime["sources"].update(comfyui_commit=commit, node_pack_commit=PINS["custom_nodes"][0]["commit"], comfyui_repo=PINS["comfyui"]["repo"], node_pack_repo=PINS["custom_nodes"][0]["repo"])
    runtime["resources"] = {"min_free_vram_mb": args.min_free_vram_mb, "min_ram_mb": args.min_ram_mb, "min_disk_gb": args.min_disk_gb, "min_session_remaining_s": args.min_session_s}
    runtime["storage"] = {"provider": "local_dir", "path": str(args.workdir / "durable")}
    runtime["python_packages"] = lt.installed_versions(("pyyaml", "jsonschema"))
    dump_yaml(root / "config" / "runtime.yaml", runtime)
    return load_project(root)


def approvals(project, approver: str):
    """Run-time approvals for the provisional test, naming the owner; returns (canon, compiled)."""
    from granthstudio.canon import load_canon
    from granthstudio.episodes import compile_episode
    from granthstudio.research import approve, load_research, require_approved
    from granthstudio.config import load_models
    from granthstudio.errors import ResearchNotApproved
    stamp = f"{approver} ({OWNER_NOTE})"
    bp.approve_provisional_canon(project, stamp)
    try:
        receipt = require_approved(project, 1)
    except ResearchNotApproved:
        approve(project, 1, stamp, datetime.now(timezone.utc).isoformat(timespec="seconds"))
        receipt = require_approved(project, 1)
    canon = load_canon(project)
    compiled = compile_episode(project, load_models(project), canon, 1, load_research(project, 1), receipt)
    return canon, compiled


def import_references(project, canon, image: Path, approver: str) -> list[dict]:
    from granthstudio import keyframes as kf
    reviewer = f"{approver} ({OWNER_NOTE}; PROVISIONAL external reference, Gemini Nano Banana painting)"
    records = []
    for asset_id, kind, canon_id, view in ((f"ref_{MAIN_CHARACTER}_front", "character_sheet", MAIN_CHARACTER, "front"), (f"ref_{LOCATION}", "location", LOCATION, "establishing")):
        asset = kf.import_asset(project, canon, asset_id, kind, canon_id, None, view, image)
        records.append(kf.approve_asset(project, canon, asset_id, asset["version"], reviewer))
    return records


def execution_extra_problems(args: argparse.Namespace) -> list[str]:
    """What the shell script also guarantees, enforced again at this entry point so a direct invocation cannot bypass it."""
    import subprocess as sp
    problems = []
    expected = os.environ.get("LTX_EXPECTED_COMMIT", "").strip()
    if not expected:
        problems.append("LTX_EXPECTED_COMMIT is not set")
    elif lt.git_head(ROOT) != expected:
        problems.append(f"GranthStudio is at {lt.git_head(ROOT)}, expected {expected}")
    if sp.run(["git", "-C", str(ROOT), "status", "--porcelain"], capture_output=True, text=True).stdout.strip():
        problems.append("the GranthStudio checkout has local modifications")
    pack = args.models_dir / "custom_nodes" / "ComfyUI_IPAdapter_plus"
    for label, path, commit in (("ComfyUI", args.models_dir, PINS["comfyui"]["commit"]), ("ComfyUI_IPAdapter_plus", pack, PINS["custom_nodes"][0]["commit"])):
        if lt.git_head(path) != commit:
            problems.append(f"{label} is not at its pinned commit {commit}")
        elif sp.run(["git", "-C", str(path), "status", "--porcelain"], capture_output=True, text=True).stdout.strip():
            problems.append(f"{label} has local modifications")
    allowed = {"ComfyUI_IPAdapter_plus", "__pycache__", "websocket_image_save.py", "example_node.py.example", ".gitignore"}
    nodes = args.models_dir / "custom_nodes"
    extra = sorted(entry.name for entry in nodes.iterdir() if entry.name not in allowed) if nodes.is_dir() else ["custom_nodes missing"]
    if extra:
        problems.append(f"unapproved entries in custom_nodes: {extra}")
    if args.worker_pid is None or args.gpu_index is None:
        problems.append("--worker-pid and --gpu-index are required: the worker's ownership of the port and its CUDA isolation are verified here")
    else:
        port = args.comfy_url.rsplit(":", 1)[-1].strip("/")
        owner = sp.run([sys.executable, str(ROOT / "scripts" / "kaggle" / "port_owner.py"), str(args.worker_pid), port], capture_output=True, text=True)
        if owner.returncode != 0:
            problems.append(f"worker pid {args.worker_pid} does not own the listener on port {port}: {(owner.stdout + owner.stderr).strip()[:160]}")
        try:
            environ = Path(f"/proc/{args.worker_pid}/environ").read_bytes().split(bytes([0]))
        except OSError as exc:
            environ = []
            problems.append(f"cannot read the worker's environment to prove its CUDA isolation: {exc}")
        if environ and f"CUDA_VISIBLE_DEVICES={args.gpu_index}".encode() not in environ:
            problems.append(f"the worker does not run with CUDA_VISIBLE_DEVICES={args.gpu_index}")
    return problems


def ssim(a: Path, b: Path) -> float | None:
    return lt._ssim(a, b)


def _run(args: argparse.Namespace, enforce_gates: bool = True) -> int:
    args.workdir.mkdir(parents=True, exist_ok=True)
    if args.gpu_index is not None:
        os.environ["GRANTHSTUDIO_GPU_INDEX"] = str(args.gpu_index)
    approver = os.environ.get("LTX_DOWNLOAD_APPROVED", "").strip()
    receipt: dict = {"schema_version": 1, "kind": "sdxl_first_keyframe_test", "started": datetime.now(timezone.utc).isoformat(timespec="seconds"), "harness_commit": lt.git_head(ROOT),
                     "approved_by": approver, "authorization_record": "docs/pilot/SDXL_DOWNLOAD_APPROVAL.md", "pins": "config/pilot_sdxl_pins.yaml", "visual": args.visual,
                     "gpu_index": args.gpu_index, "workdir": str(args.workdir), "comfy_url": args.comfy_url, "worker_pid": args.worker_pid,
                     "cuda_visible_devices_of_worker": args.cuda_visible_devices, "style": "devotional_gouache_1950s_v1",
                     "reference_image": {"path": str(args.reference_image), "sha256": lt.sha256_file(args.reference_image), "role": "PROVISIONAL external identity/style reference (not an SDXL output)"},
                     "note": "A PASS means technically valid images through the existing pipeline. Style fidelity and identity are judged by a human; the reference never validates SDXL itself."}

    def finish(verdict: str, reason: str) -> int:
        receipt.update(verdict=verdict, reason=reason, finished=datetime.now(timezone.utc).isoformat(timespec="seconds"), comfyui_log_excerpt=lt.comfy_log_excerpt(args.comfy_log))
        (args.workdir / "sdxl_receipt.json").write_text(json.dumps(receipt, indent=2, default=str), encoding="utf-8")
        print(f"VERDICT: {verdict} - {reason}\nreceipt: {args.workdir / 'sdxl_receipt.json'}")
        return 0 if verdict == "PASS" else 1

    if enforce_gates:
        problems = lt.execution_gate_problems(argparse.Namespace(skip_static_verify=False, gpu_index=args.gpu_index, allow_other_gpu_busy=args.allow_other_gpu_busy,
                                                                 other_gpu_idle_mb=args.other_gpu_idle_mb, min_session_s=args.min_session_s))
        if not approver:
            problems.append("LTX_DOWNLOAD_APPROVED (the approver's name) is not set")
        problems += execution_extra_problems(args)
        if problems:
            return finish("NOT_RUN", "execution gate: " + "; ".join(problems))
    if not args.reference_image.is_file():
        return finish("NOT_RUN", f"reference image {args.reference_image} is missing")
    problems = verify_files(args.models_dir)
    receipt["file_check"] = {"problems": problems, "pinned": [{"name": i["name"], "sha256": i["sha256"], "size_bytes": i["size_bytes"], "revision": i["revision"]} for i in PINS["files"]]}
    if problems:
        return finish("NOT_RUN", "pinned files not as pinned: " + "; ".join(problems))
    from granthstudio import keyframes as kf
    from granthstudio.comfy import ComfyBackend, load_template, render_graph
    from granthstudio.config import load_models
    from granthstudio.errors import GranthError
    from granthstudio.integrity import read_json
    from granthstudio.runtime import gate_gpu_tasks, gpu_status, load_runtime, preflight, ram_available_mb
    try:
        project = prepare_project(args)
    except RuntimeError as exc:
        return finish("NOT_RUN", str(exc))
    canon, compiled = approvals(project, approver or "synthetic-tester")
    receipt["provisional_approvals"] = f"research, canon and the two reference assets approved at run time for the provisional technical test by '{approver}' ({OWNER_NOTE})"
    records = import_references(project, canon, args.reference_image, approver or "synthetic-tester")
    receipt["reference_assets"] = [{k: r[k] for k in ("asset_id", "version", "sha256", "view", "status", "approved_by")} for r in records]
    models = load_models(project)
    registry = kf.load_registry(project, canon)
    request = kf.keyframe_request(compiled, canon, registry, models, args.visual)
    receipt["request"] = {k: request[k] for k in ("asset_id", "visual_id", "role", "characters", "locations", "props", "lighting", "seed", "width", "height", "style", "template_version",
                                                  "missing_references", "request_sha256")}
    receipt["request"].update(prompt=request["prompt"], negative_prompt=request["negative_prompt"], references=[{"asset_id": r["asset_id"], "sha256": r["sha256"]} for r in request["references"]])
    if request["missing_references"]:
        return finish("NOT_RUN", f"missing approved references {request['missing_references']}")
    report = preflight(project, models, load_runtime(project), gpu_status(), ram_available_mb())
    receipt["preflight"] = report
    if not args.execute:
        return finish("NOT_RUN", f"dry run (no --execute); preflight gpu_ready={report['gpu_ready']}")
    if not report["gpu_ready"]:
        return finish("NOT_RUN", f"GPU preflight not passed: {[k for k, v in report['checks'].items() if v['status'] not in ('pass', 'info')]}")
    # live compatibility: the graph's node classes and every loader file name must exist on THIS server before anything is submitted
    template = load_template(project.root / "workflows" / "comfyui" / "sdxl_keyframe.json")
    probe_values = {"PROMPT": "p", "NEGATIVE_PROMPT": "n", "SEED": 1, "WIDTH": 64, "HEIGHT": 64, **{f"REFERENCE_IMAGE_{i}": "x.png" for i in range(1, 6)}}
    backend = ComfyBackend(args.comfy_url)
    try:
        probe = render_graph(template, probe_values)
        backend.require_nodes(probe)
        backend.require_model_files({k: v for k, v in probe.items() if v["class_type"] != "LoadImage"})
    except GranthError as exc:
        receipt["live_check"] = {"ok": False, "detail": str(exc)}
        return finish("NOT_VALIDATED", f"live node/model check failed: {exc}")
    receipt["live_check"] = {"ok": True, "node_classes": sorted({v["class_type"] for v in probe.values()})}
    out = args.workdir / "outputs"
    out.mkdir(exist_ok=True)
    results = {}
    began = time.monotonic()
    receipt["exec_started"] = datetime.now(timezone.utc).isoformat(timespec="milliseconds")
    runs = [("with_reference", request)]
    if not args.skip_control:
        control = {**request, "references": [], "asset_id": request["asset_id"] + "_noref"}
        control["request_sha256"] = hashlib.sha256(json.dumps({k: v for k, v in control.items() if k != "request_sha256"}, sort_keys=True, default=str).encode()).hexdigest()
        runs.append(("no_reference_control", control))
    for label, req in runs:
        work = args.workdir / f"work_{label}"
        shutil.rmtree(work, ignore_errors=True)
        work.mkdir(parents=True)
        journal = project.artifacts_dir / "tasks" / "pending" / f"{label}.json"
        journal.parent.mkdir(parents=True, exist_ok=True)
        started = time.monotonic()
        try:
            kf.sdxl_generate(project, models, req, journal, work)
        except GranthError as exc:
            oom = lt.oom_markers(args.comfy_log, str(exc))
            receipt["out_of_memory"] = bool(oom)
            results[label] = {"error": f"{type(exc).__name__}: {exc}"}
            receipt["results"] = results
            return finish("FAIL", ("CUDA out of memory; not retried. " if oom else "") + f"{label}: {exc}")
        image = out / f"{label}.png"
        shutil.copyfile(work / "keyframe.png", image)
        metrics = read_json(work / "metrics.json")
        results[label] = {"image": image.name, "sha256": lt.sha256_file(image), "wall_s": round(time.monotonic() - started, 1), "request_sha256": req["request_sha256"],
                          "reference_count": len(req["references"]), "journal": read_json(journal), "metrics": metrics}
    receipt["exec_finished"] = datetime.now(timezone.utc).isoformat(timespec="milliseconds")
    receipt["wall_s"] = round(time.monotonic() - began, 1)
    receipt["results"] = results
    from granthstudio.ffmpeg import probe as probe_media
    for label, item in results.items():
        info = probe_media(out / item["image"])
        item["decoded"] = {"width": info.width, "height": info.height}
        if (info.width, info.height) != (request["width"], request["height"]):
            return finish("FAIL", f"{label}: decoded {info.width}x{info.height}, requested {request['width']}x{request['height']}")
    sheet = out / "contact_sheet.png"
    inputs = [args.reference_image, out / "with_reference.png"] + ([out / "no_reference_control.png"] if "no_reference_control" in results else [])
    done = subprocess.run(["ffmpeg", "-y", "-v", "error", *sum((["-i", str(p)] for p in inputs), []), "-filter_complex",
                           "".join(f"[{i}:v]scale=-1:512[v{i}];" for i in range(len(inputs))) + "".join(f"[v{i}]" for i in range(len(inputs))) + f"hstack=inputs={len(inputs)}",
                           "-frames:v", "1", str(sheet)], capture_output=True, text=True, timeout=120)
    receipt["contact_sheet"] = {"file": sheet.name if done.returncode == 0 else None, "order": "reference painting | with reference | no-reference control"}
    if "no_reference_control" in results:
        receipt["reference_influence"] = {"ssim_with_reference_vs_control": ssim(out / "with_reference.png", out / "no_reference_control.png"),
                                          "identical_bytes": results["with_reference"]["sha256"] == results["no_reference_control"]["sha256"],
                                          "ssim_with_reference_vs_reference_image": ssim(out / "with_reference.png", args.reference_image),
                                          "note": "numbers are evidence for the reviewer, not an acceptance; identical bytes would mean the reference had NO effect"}
        if receipt["reference_influence"]["identical_bytes"]:
            return finish("FAIL", "the reference image had no effect: the images with and without it are byte-identical")
    return finish("PASS", "keyframe image(s) generated and decoded through the existing pipeline with the live node check passed; style, identity and likeness await human review")


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    return _run(args, enforce_gates=args.execute)


if __name__ == "__main__":
    sys.exit(main())
